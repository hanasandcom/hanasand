import assert from 'node:assert/strict'

export async function runLiveWorkspaceJourney(context) {
    const { page, server, fixture, image, viewport, loading } = context
    await page.evaluate(image => window.deliver({ type: 'frame', image, width: 1280, height: 720, url: 'https://example.com', reason: 'load', networkSummary: { requestCount: 125, uniqueDomainCount: 18, failedCount: 0 } }), image)
    await page.evaluate(() => window.deliver({ type: 'site_network', site: { url: 'https://example.com', ip: '93.184.215.14', country: 'Australia', country_code: 'AU' } }))
    const ipLink = page.getByRole('link', { name: '93.184.215.14 on VirusTotal (opens in a new tab)' })
    assert.equal(await ipLink.getAttribute('href'), 'https://www.virustotal.com/gui/ip-address/93.184.215.14')
    assert.equal(await ipLink.getAttribute('target'), '_blank')
    assert.equal(await ipLink.getByRole('img', { name: 'Australia' }).textContent(), '🇦🇺')

    await page.locator('summary').filter({ hasText: /^Network \/ requests/ }).getByText('125', { exact: true }).waitFor()
    assert.equal(await page.getByText('No high-signal malicious pattern was extracted from the rendered page yet.', { exact: true }).count(), 0)
    await page.evaluate(() => {
        window.deliver({ type: 'site_network', site: { url: 'https://example.com', ip: '93.184.215.14', provider: 'Example Network', city: 'Oslo', country: 'Norway' } })
        window.deliver({ type: 'stream_metrics', fps: 60, latencyMs: 22 })
    })
    await page.getByText('· 93.184.215.14', { exact: true }).waitFor()
    assert(await page.getByText('· Example Network', { exact: true }).isVisible())
    assert(await page.getByText('· Oslo, Norway', { exact: true }).isVisible())
    assert.equal(await page.getByLabel('Ping: 22 milliseconds').getAttribute('title'), 'Ping')
    assert.equal(await page.getByRole('tab', { name: /^WebCrack/ }).count(), 0)
    const box = await viewport.boundingBox()
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
    const pointers = await page.evaluate(() => window.browserMessages.filter(message => message.type === 'pointer'))
    assert.equal(pointers.filter(message => message.event === 'pointerdown').length, 1)
    assert.equal(pointers.filter(message => message.event === 'pointerup').length, 1)
    assert(Math.abs(pointers.at(-1).x - 640) < 2 && Math.abs(pointers.at(-1).y - 360) < 2, 'Map the contained image, not letterbox space')
    assert.equal(await page.evaluate(() => window.browserMessages.filter(message => message.type === 'click').length), 0, 'A pointer click must not also send a duplicate click command')
    await page.mouse.wheel(0, 180)
    await page.waitForFunction(() => window.browserMessages.some(message => message.type === 'wheel' && message.deltaY === 180))
    await page.evaluate(url => window.deliver({ type: 'stream_ready', streamUrl: url }), `${server.url}stream/index.html`)
    const iframe = page.getByTitle('Live WebRTC browser sandbox')
    await iframe.waitFor({ state: 'attached' })
    assert(await page.getByAltText('Live browser sandbox frame').isVisible(), 'Keep the available screenshot visible while video connects')
    assert.equal(await iframe.evaluate(element => getComputedStyle(element).visibility), 'visible', 'Do not hide an autoplay video while waiting for playback')
    const frame = page.frameLocator('iframe')
    await frame.getByRole('button', { name: 'Remote click' }).waitFor()
    assert((await viewport.boundingBox()).height > 300, 'A connected stream must have a usable viewport even before its readiness message')
    const nativeFrame = page.frames().find(frame => frame.url().includes('/stream/index.html'))
    await nativeFrame.evaluate(() => parent.postMessage({ type: 'hanasand-browser-stream', state: 'gesture' }, location.origin))
    await page.getByText('Tap to resume', { exact: true }).waitFor()
    assert(await page.getByAltText('Live browser sandbox frame').isVisible(), 'A gesture prompt must not count as a video frame')
    await nativeFrame.evaluate(() => { const signal = () => parent.postMessage({ type: 'hanasand-browser-stream', state: 'ready' }, location.origin); signal(); window.heartbeat = setInterval(signal, 1000) })
    await page.waitForFunction(() => document.querySelector('[data-browser-viewport]').getBoundingClientRect().height > 300)
    await page.getByAltText('Live browser sandbox frame').waitFor({ state: 'detached' })
    for (const name of ['VirusTotal', 'urlquery', 'example.com', 'VirusTotal', 'example.com']) await page.getByRole('tab', { name: new RegExp(`^${name}`) }).click()
    await page.evaluate(() => window.deliver({ type: 'tool_capture', id: 'webcrack', name: 'WebCrack', url: 'https://webcrack.netlify.app/', deobfuscatedCode: 'console.log("decoded");', toolAnalysis: { toolKind: 'webcrack', webcrackLoaded: true }, webcrackLoad: { loaded: true } }))
    await page.getByRole('tab', { name: /^WebCrack/ }).click()
    await viewport.getByText('console.log("decoded");', { exact: true }).waitFor()
    await page.getByRole('tab', { name: /^example.com/ }).click()
    const beforeInput = await page.evaluate(() => window.browserMessages.length)
    await frame.getByRole('button', { name: 'Remote click' }).click()
    assert.equal(await nativeFrame.evaluate(() => window.remoteClicks), 1)
    assert.equal(await page.evaluate(() => window.browserMessages.length), beforeInput, 'Native stream input must not also use screenshot input forwarding')
    const streamBox = await iframe.boundingBox()
    await page.mouse.move(streamBox.x + 150, streamBox.y + 100)
    await page.mouse.wheel(0, 300)
    await nativeFrame.waitForFunction(() => scrollY > 0)
    await page.getByRole('tab', { name: /^example.com/ }).focus()
    await page.keyboard.press('ArrowRight')
    assert.equal(await page.getByRole('tab', { name: /^VirusTotal/ }).getAttribute('aria-selected'), 'true')
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile workspace must not overflow horizontally')
    assert.equal(fixture.streamLoads, 1, 'Tool changes, deobfuscated code, and responsive changes preserve the stream')
    if (process.env.BROWSER_WORKSPACE_SCREENSHOT) {
        await page.setViewportSize({ width: 1440, height: 900 })
        await page.screenshot({ path: process.env.BROWSER_WORKSPACE_SCREENSHOT.replace('.png', '-live.png'), fullPage: true })
        await page.setViewportSize({ width: 390, height: 844 })
    }
    const mobileViewport = await viewport.boundingBox()
    assert(mobileViewport.x + mobileViewport.width <= 390, `Viewport clipped at ${mobileViewport.x + mobileViewport.width}px`)
    await page.evaluate(() => window.deliver({ type: 'downloads', networkSummary: { requestCount: 8, uniqueDomainCount: 2, downloads: [{ id: 'file-1', fileName: 'sample.txt', sha256: 'a'.repeat(64), bytes: 32, virusTotal: { status: 'checking' } }] } }))
    await page.getByText('sample.txt', { exact: true }).waitFor()
    await page.evaluate(() => window.deliver({ type: 'downloads', networkSummary: { requestCount: 8, uniqueDomainCount: 2, downloads: [{ id: 'file-1', fileName: 'sample.txt', sha256: 'a'.repeat(64), bytes: 32, virusTotal: { status: 'known', flagged: 2, total: 70 } }] } }))
    await page.getByText('VirusTotal 2/70 detections', { exact: true }).waitFor()
    Object.assign(context, { viewport, loading, iframe, frame, nativeFrame })
}
