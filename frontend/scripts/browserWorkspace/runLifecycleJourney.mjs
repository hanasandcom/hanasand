import assert from 'node:assert/strict'

export async function runRunLifecycleJourney(context) {
    const { page, server, fixture, image, loading, iframe, result } = context
    await page.getByRole('button', { name: 'Run another' }).click()
    assert.equal(new URL(page.url()).pathname, '/sandbox')
    assert(await page.getByRole('button', { name: 'History', exact: true }).isVisible(), 'Return shows the landing page')
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await loading.waitFor()
    const freshNavigation = page.waitForEvent('framenavigated', { predicate: frame => frame.url().includes('/stream/index.html') })
    await page.evaluate(url => window.deliver({ type: 'stream_ready', streamUrl: url }), `${server.url}stream/index.html`)
    await iframe.waitFor({ state: 'attached' })
    const freshFrame = await freshNavigation
    assert(await loading.isVisible(), 'A stream URL alone is not a first frame')
    await freshFrame.evaluate(() => parent.postMessage({ type: 'hanasand-browser-stream', state: 'ready' }, location.origin))
    await loading.waitFor({ state: 'detached' })
    assert.equal(fixture.streamLoads, 2, 'Revealing the workspace must not reload the stream')
    await page.evaluate(() => window.deliver({ type: 'stream_metrics', fps: 60, latencyMs: 22 }))
    const statusRow = page.locator('[data-browser-status]')
    assert((await statusRow.boundingBox()).y > (await page.getByRole('button', { name: 'Export', exact: true }).boundingBox()).y, 'Capacity and telemetry sit below the actions')
    await page.clock.setFixedTime(new Date(Date.now() + 30_000))
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    await page.getByText('Run done', { exact: true }).waitFor()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('hanasand:browser:history:v1') || '[]').some(run => run.status === 'completed' && run.reportUrl), null, { timeout: 5000 })
    assert.equal(await statusRow.count(), 0, 'Completed runs hide header telemetry')
    await page.getByRole('button', { name: /Open report/ }).click()
    const statistics = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Statistics$/ }) })
    await statistics.locator('summary').click()
    assert((await statistics.innerText()).includes('Stopped · 60 FPS · 22ms'), 'Completed telemetry remains in Statistics')
    assert.equal(await page.getByText('Connection and provider details', { exact: true }).count(), 0)
    assert.equal(await iframe.count(), 0, 'Stop removes the stream immediately without waiting for the server')
    await page.getByRole('button', { name: 'Run another' }).click()
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await loading.waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await loading.waitFor({ state: 'detached' })
    await result.waitFor()
    await page.getByText('Run cancelled', { exact: true }).waitFor()
    await page.evaluate(() => window.deliver({ type: 'ready' }))
    assert.equal(await loading.count(), 0, 'Late worker messages must not restart a cancelled run')
    assert(await page.evaluate(() => window.browserMessages.some(message => message.type === 'end')), 'Cancel must request worker teardown')
    await page.getByRole('button', { name: 'Run another' }).click()
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    // Policy failures remain terminal; a lost worker is replaced automatically.
    await page.evaluate(() => window.deliver({ type: 'status', state: 'quota_exhausted', message: 'Browser run limit reached.' }))
    await loading.waitFor({ state: 'detached' })
    await page.getByText('Run failed', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.evaluate(image => { window.deliver({type: 'ready'}); window.deliver({ type: 'frame', image, url: 'https://example.com' }) }, image)
    await loading.waitFor({ state: 'detached' })
    let starts = await page.evaluate(() => window.browserMessages.filter(message => message.type === 'start').length)
    for (const failure of ['unavailable', 'launch-failed', 'connection-error']) {
        await page.evaluate(failure => {
            if (failure === 'unavailable') window.deliver({ type: 'resume_unavailable' })
            else if (failure === 'connection-error') window.deliver({ type: 'error', message: 'Isolated browser worker connection failed.' })
            else window.deliver({ type: 'ended', reason: 'launch_failed' })
        }, failure)
        assert.equal(await page.getByText('Run failed', { exact: true }).count(), 0, 'Recoverable failure does not show a failed summary')
        await page.waitForFunction(count => window.browserMessages.filter(message => message.type === 'start').length > count, starts)
        starts++
        await page.evaluate(() => window.deliver({type: 'ready'}))
        await page.getByAltText('Live browser sandbox frame').waitFor()
        assert.equal(await page.getByAltText('Live browser sandbox frame').getAttribute('src'), `data:image/jpeg;base64,${image}`, 'Replacement preserves collected evidence')
    }
    await page.evaluate(() => window.deliver({type:'resume_unavailable'}))
    await page.getByRole('button', {name:'Stop',exact:true}).click()
    await page.waitForTimeout(1100)
    assert.equal(await page.evaluate(() => window.browserMessages.filter(message => message.type === 'start').length), starts, 'Stop cancels pending replacement')
    await result.click()
    await page.getByText('Analyst notes and captures', {exact:true}).click()
    const screenshotList = page.locator('[data-screenshot-list]')
    assert.equal(await screenshotList.evaluate(el => getComputedStyle(el).maxHeight), 'none', 'Screenshots expand down the page without a nested scroll cap')
    assert.equal(await screenshotList.evaluate(el => el.scrollHeight <= el.clientHeight + 1), true, 'Every screenshot fits in the expanded list')
}
