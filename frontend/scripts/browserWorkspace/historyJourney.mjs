import assert from 'node:assert/strict'

export async function runHistoryJourney(context) {
    const { page, server, fixture, loading } = context
    const storedRun = { id: 'recent-run', resultId: 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee', target: 'https://example.com', network: 'regular', status: 'completed', startedAt: '2026-01-01T00:00:00Z' }
    fixture.setRecentRuns([storedRun])
    await page.goto(server.url.toString())
    assert.equal(await page.getByRole('button', { name: 'Run again', exact: true }).count(), 0, 'History has no rerun button')
    const historyRow = page.getByRole('link', { name: /https:\/\/example.com/ })
    assert.equal(await historyRow.getAttribute('href'), `/sandbox/${storedRun.resultId}`)
    await historyRow.click()
    await page.getByRole('heading', { name: 'https://example.com', exact: true }).waitFor()
    assert.equal(await page.getByRole('dialog').count(), 0, 'Stored evidence is a page, not a popup')
    assert.equal(await page.evaluate(() => window.browserMessages.length), 0, 'Opening archived results never starts a worker')
    await page.getByLabel('Saved run', { exact: true }).selectOption('older-run')
    await page.getByRole('heading', { name: 'https://example.com', exact: true }).waitFor()
    assert.equal(await page.getByLabel('Saved run', { exact: true }).inputValue(), 'older-run')
    await page.reload()
    await page.getByRole('heading', { name: 'https://example.com', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.browserMessages.length), 0)
    await page.getByRole('button', { name: 'Run again', exact: true }).click()
    await loading.waitFor()
    await page.waitForFunction(() => window.browserMessages.some(message => message.type === 'start'))
    await page.reload()
    await page.getByRole('button', { name: 'Quick run', exact: true }).click()
    await page.waitForFunction(() => window.browserMessages.some(message => message.type === 'start'))
    assert.equal(await page.evaluate(() => window.browserMessages.find(message => message.type === 'start').durationSeconds > 10), true)
    await page.evaluate(() => window.deliver({ type: 'tool_capture', id: 'virustotal', url: 'https://www.virustotal.com/', toolAnalysis: { toolKind: 'virustotal', vendorFlagged: 0, vendorTotal: 90 } }))
    assert.equal(await page.evaluate(() => window.browserMessages.some(message => message.type === 'end')), false, 'Wait for both providers')
    await page.evaluate(() => window.deliver({ type: 'tool_capture', id: 'urlquery', url: 'https://urlquery.net/', error: 'provider_navigation_pending', toolAnalysis: { toolKind: 'urlquery', verdict: 'unknown' } }))
    assert.equal(await page.evaluate(() => window.browserMessages.some(message => message.type === 'end')), false, 'Pending captures are not results')
    await page.evaluate(() => window.deliver({ type: 'tool_capture', id: 'urlquery', url: 'https://urlquery.net/', toolAnalysis: { toolKind: 'urlquery', alertCount: 0 } }))
    await page.waitForFunction(() => window.browserMessages.some(message => message.type === 'end'))
    assert.equal(await page.evaluate(() => window.browserMessages.filter(message => message.type === 'end').length), 1)
    assert.equal(await page.getByText('Run cancelled', { exact: true }).count(), 0)
    await page.goto(server.url.toString())
    assert.equal(fixture.historyRequests, 0, 'Full history loads only on demand')
    await page.getByRole('button', { name: 'History', exact: true }).click()
    const historyDialog = page.getByRole('dialog', { name: 'History', exact: true })
    await page.waitForFunction(() => document.querySelectorAll('dialog a').length === 50)
    assert.equal(await historyDialog.getByRole('link').count(), 50)
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await historyDialog.evaluate(element => element.getBoundingClientRect().right <= innerWidth), 'History fits mobile')
    await historyDialog.evaluate(element => element.scrollTo({ top: element.scrollHeight, behavior: 'instant' }))
    await page.waitForFunction(() => document.querySelectorAll('dialog a').length === 51)
    await page.keyboard.press('Escape')
    assert.equal(await historyDialog.isVisible(), false)
    await page.getByRole('button', { name: 'History', exact: true }).click()
    await historyDialog.locator('a[href$="run=older-run"]').click()
    await page.getByRole('heading', { name: 'https://example.com', exact: true }).waitFor()
    assert.equal(await page.getByLabel('Saved run', { exact: true }).inputValue(), 'older-run')
    assert.equal(await page.getByRole('button', { name: 'History', exact: true }).evaluate(element => getComputedStyle(element).position), 'static', 'Saved-result history is in the header, not floating')
}
