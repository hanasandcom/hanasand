import assert from 'node:assert/strict'

export async function checkVmInventoryUx(page, base) {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(base + '/vms', { waitUntil: 'load' })
    const filterButton = page.getByRole('button', { name: 'Filter virtual machines' })
    await filterButton.click()
    const filterPanel = page.getByRole('region', { name: 'Filter virtual machines' })
    await filterPanel.waitFor()
    await page.getByRole('searchbox', { name: 'Name' }).fill('recoverable')
    assert.equal(await page.getByText('1 of 3 virtual machines').count(), 1)
    assert.equal(await page.getByRole('heading', { name: 'hydration-recoverable-vm' }).count(), 1)
    await page.getByRole('searchbox', { name: 'Name' }).fill('')
    await page.getByLabel('Editors').selectOption('ada')
    assert.equal(await page.getByRole('heading', { name: 'hydration-vm' }).count(), 1)
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    await page.getByLabel('Minimum CPU').selectOption('2')
    assert.equal(await page.getByText('3 virtual machines').count(), 1)
    await page.getByLabel('Minimum memory').selectOption('2')
    assert.equal(await page.getByText('3 virtual machines').count(), 1)
    await page.getByLabel('Deletion').selectOption('scheduled')
    assert.equal(await page.getByText('2 of 3 virtual machines').count(), 1)
    const panelBounds = await filterPanel.boundingBox()
    assert(panelBounds && panelBounds.x >= 0 && panelBounds.x + panelBounds.width <= 390, `filter panel must fit the iPhone viewport: ${JSON.stringify(panelBounds)}`)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'VM filters must not create horizontal page overflow on iPhone')
    await page.keyboard.press('Escape')
    assert.equal(await filterPanel.count(), 0)

    await page.setViewportSize({ width: 768, height: 1024 })
    await filterButton.click()
    const tabletBounds = await filterPanel.boundingBox()
    assert(tabletBounds && tabletBounds.x >= 0 && tabletBounds.x + tabletBounds.width <= 768, 'filter panel must fit the iPad viewport')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'VM filters must not create horizontal page overflow on iPad')
    await page.keyboard.press('Escape')

    await page.setViewportSize({ width: 1280, height: 900 })
    await filterButton.click()
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    const restart = page.getByRole('button', { name: 'Restart hydration-vm' })
    await restart.waitFor({ state: 'visible' })
    const row = page.locator('article').filter({ has: page.getByRole('heading', { name: 'hydration-vm' }) }).first()
    const rowBefore = await row.boundingBox()
    await restart.click()
    await page.getByRole('status').filter({ hasText: 'Restart requested for hydration-vm.' }).waitFor()
    assert.deepEqual(await row.boundingBox(), rowBefore, 'VM action feedback must not shift the inventory row')
    assert.equal(await row.getByText('Restart requested for hydration-vm.').count(), 0, 'VM action feedback must stay outside the row')
}
