import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()

test('dashboard DWM keeps scoped workflow and durable delivery wording', async () => {
    const dwmPage = await readFile(path.join(root, 'src/app/dashboard/findings/page.tsx'), 'utf8')
    const dwmPortal = await readFile(path.join(root, 'src/app/dashboard/findings/findings.tsx'), 'utf8')
    const dashboardPage = await readFile(path.join(root, 'src/app/dashboard/page.tsx'), 'utf8')
    const dashboardOverviewPage = await readFile(path.join(root, 'src/app/dashboard/overview/page.tsx'), 'utf8')
    const workflowActions = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-actions.tsx'), 'utf8')
    const workflowRouteDashboard = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-route-dashboard.tsx'), 'utf8')
    const workflowRouteSummary = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-route-summary.tsx'), 'utf8')
    const workflowDeliveryActions = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-delivery-actions.ts'), 'utf8')
    const workflowEvidenceActions = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-evidence-actions.ts'), 'utf8')
    const workflowRouteCard = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-route-card.tsx'), 'utf8')
    const workflowValues = await readFile(path.join(root, 'src/app/dashboard/findings/workflow-values.ts'), 'utf8')
    const workbenchActionMessages = await readFile(path.join(root, 'src/app/dashboard/ti/workbench/modules/actionMessages.ts'), 'utf8')
    const caseActions = await readFile(path.join(root, 'src/app/dashboard/cases/[id]/case-detail/useCaseDetailActions.ts'), 'utf8')
    const caseDelivery = await readFile(path.join(root, 'src/app/dashboard/cases/[id]/case-detail/CaseDeliveryPanels.tsx'), 'utf8')

    expect(dwmPage).toContain('<Findings')
    expect(dwmPage).toContain('snapshot={loadingSnapshot(tenantId)}')
    expect(dwmPage).toContain('dataHealth={loadingDataHealth()}')
    expect(dwmPage).toContain('const view = normalizeDwmView(firstSearchParam(params?.panel))')
    expect(dwmPage).toContain('view={view}')
    expect(dwmPage).not.toContain('mergeDwmAlerts')
    expect(dwmPortal).not.toContain('fallbackAlerts')
    expect(dashboardPage).toContain('export { default, dynamic, metadata } from \'./overview/page\'')
    expect(workflowRouteDashboard).toContain('<RouteRunSummary route={lastRoute} organizationId={organizationId} />')
    expect(workflowRouteSummary).toContain('export function deliveryLogHref(organizationId: string, alertId?: string)')
    expect(workflowRouteSummary).toContain('return `/findings/delivery?${params.toString()}`')
    expect(workflowRouteSummary).toContain('new URLSearchParams({ org: organizationId })')
    expect(workflowRouteSummary).toContain('deliveryLogHref(organizationId, route.alertId)')
    expect(workflowRouteSummary).toContain('params.set(\'alert\', alertId)')
    expect(workflowRouteSummary).toContain('Open delivery log')
    expect(workflowRouteSummary).toContain('event linked')
    expect(workflowRouteDashboard).toContain('data-dwm-workflow-result-action=\'true\'')
    expect(workflowRouteSummary).toContain('export function deliverySetupHref(organizationId?: string)')
    expect(workflowRouteSummary).toContain('findingsActionsHref(organizationId)')
    expect(workflowRouteSummary).toContain(': \'#dwm-inline-webhook\'')
    expect(workflowEvidenceActions).toContain('deliverySetupHref(organizationId)')
    expect(workflowActions).toContain('No destination yet. Add or test an HTTPS Discord/webhook endpoint before sending.')
    expect(workflowRouteDashboard).toContain('Test saves a delivery attempt without sending externally.')
    expect(workflowDeliveryActions).toContain('webhookUrl: context.webhookConfigured ? webhookUrl.trim() : undefined')
    expect(workflowActions).toContain('Enter an HTTPS webhook URL or open an organization with a saved delivery destination before sending queued events.')
    expect(workflowRouteCard).toContain('data-dwm-command-disabled-reason=\'true\'')
    expect(workflowRouteCard).toContain('{action.disabledReason}')
    expect(workflowValues).toContain('function rebuiltAlertSummary(alert: Record<string, unknown>)')
    expect(workflowValues).toContain('formatClaimSummary(readString(alert.claimSummary)')
    expect(workflowRouteSummary).not.toContain('{route.alertId}</span>')
    expect(workflowValues).not.toContain('const summary = readString(alert.claimSummary).toLowerCase()')
    expect(workflowDeliveryActions).toContain('No durable delivery result was returned.')
    expect(workflowDeliveryActions).toContain('Webhook delivery recorded a dry-run; no customer notification was sent.')
    expect(workflowDeliveryActions).toContain('Webhook delivery recorded a failed attempt.')
    expect(workflowDeliveryActions).not.toContain('Webhook delivery attempted for ${attemptedCount} alert(s).')
    expect(workflowDeliveryActions).toContain('Webhook test recorded a dry-run delivery.')
    expect(workflowDeliveryActions).toContain('Webhook test recorded a failed delivery attempt.')
    expect(workbenchActionMessages).not.toContain('Webhook delivery attempted for ${payload.attemptedCount} alert')
    expect(caseActions).toContain('reportFormat: \'stix\'')
    expect(caseActions).toContain('No durable delivery result was returned.')
    expect(caseDelivery).toContain('Hanasand receiver receipt')

    expect(dashboardOverviewPage).not.toContain('DWM alerts returned HTTP')
    expect(dashboardOverviewPage).not.toContain('What returned')
    expect(workflowDeliveryActions).not.toContain('No delivery was ready')
    expect(workflowDeliveryActions).not.toContain('Delivery was not ready')
    expect(workflowRouteDashboard).not.toContain('Stage a webhook when the case needs customer notification.')
    expect(workflowRouteDashboard).not.toContain('Every command calls the DWM API')
    expect(workflowRouteDashboard).not.toContain('Dry-run uses this endpoint and records the delivery result without external send by default.')
    expect(workflowRouteDashboard).not.toContain('Paste an HTTPS Discord or webhook endpoint before testing customer delivery.')
})

test('product progress uses persisted evidence instead of synthetic readiness rows', async () => {
    const response = await readFile(path.join(root, 'src/app/api/product-progress/response.ts'), 'utf8')

    expect(response).not.toMatch(/synthetic(?:Organization|Webhook|Deliveries|Cases|Analyst|Support)/)
    expect(response).not.toContain('sourceCount < 1000')
    expect(response).toContain('const organizationProof = organizationReadinessProof(organizationReadiness)')
    expect(response).toContain('const selectedCaseProof = analystCaseDetailProof(selectedCaseDetail')
})
