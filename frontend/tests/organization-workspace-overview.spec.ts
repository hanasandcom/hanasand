import { expect, test } from '@playwright/test'
import { setupOrganizationWorkspace } from './organization-workspace-harness'

test('organization workspace summary readiness settings and organization search', async ({ context, page, baseURL }) => {
    const state = await setupOrganizationWorkspace(context, page, baseURL)
    await expect(page.getByRole('heading', { name: 'Organization settings', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: /Acme Security owner/ })).toBeVisible()
    await expect(page.locator('[data-org-workspace-summary="true"]')).toBeVisible()
    await expect(page.locator('[data-org-summary-chip="members"]')).toContainText('3')
    await expect(page.locator('[data-org-summary-chip="watchlists"]')).toContainText('1')
    await expect(page.locator('[data-org-summary-chip="role"]')).toContainText('Owner')
    await expect(page.locator('[data-org-summary-chip="role"]')).not.toContainText('active')
    await expect(page.locator('[data-org-summary-chip="watchlists"]')).toContainText('paused')
    await expect(page.locator('[data-org-summary-chip="watchlists"]')).not.toContainText('archived')
    await expect(page.locator('[data-org-summary-chip="destinations"]')).not.toContainText('Routes')
    await expect(page.locator('[data-org-section-nav="true"]')).toBeVisible()
    await expect(page.locator('[data-org-section-nav-item="team"]')).toContainText('3 active')
    await expect(page.locator('[data-org-section-nav-item="watchlists"]')).toContainText('1 active')
    await expect(page.locator('[data-org-section-nav-item="destinations"]')).toContainText('1 configured')
    await expect(page.locator('[data-org-section-nav-item="delivery"]')).toContainText('15 events')
    await expect(page.locator('[data-org-health-compact="true"]')).toBeVisible()
    await expect(page.locator('[data-org-health-row="access"]')).toContainText('3 members')
    await expect(page.locator('[data-org-health-row="delivery"]')).toContainText('15 notifications')
    await expect(page.locator('[data-org-health-row="delivery"]')).toHaveAttribute('href', '/cases/case_acme_1?organizationId=org_acme&alertId=dwm_alert_acme')
    await expect(page.locator('[data-org-summary-chip="members"] a')).toHaveText('1 pending')
    await expect(page.locator('[data-org-summary-chip="members"] a')).toHaveAttribute('href', '/organizations/team#invites')
    await expect(page.locator('[data-org-summary-chip="watchlists"] a')).toHaveText('1 paused')
    await expect(page.locator('[data-org-summary-chip="watchlists"] a')).toHaveAttribute('href', '/organizations/watchlists#watchlists')
    await expect(page.locator('[data-org-health-strip="true"]')).toContainText('Last activity')
    await expect(page.locator('[data-org-setup-rail="true"]')).toBeVisible()
    await expect(page.locator('[data-org-setup-progress-count="true"]')).toContainText('4/4')
    await expect(page.locator('[data-org-pilot-metrics="true"]')).toBeVisible()
    await expect(page.locator('[data-org-pilot-metric="coverage"]')).toContainText('1 active term')
    await expect(page.locator('[data-org-pilot-metric="precision"]')).toContainText('Not measured')
    await expect(page.locator('[data-org-pilot-metric="triage"]')).toContainText('Not measured')
    await expect(page.locator('[data-org-setup-step="destinations"]')).toContainText('2 destinations')
    await expect(page.locator('[data-org-setup-step="team"]')).toContainText('3 active members')
    await expect(page.locator('[data-org-setup-next="true"]')).toContainText('Review invites')
    await page.locator('#settings').getByLabel('Name').fill('Acme Security Ops')
    await page.locator('#settings').getByRole('button', { name: 'Save settings' }).click()
    expect(state.settingsUpdates).toContainEqual({ name: 'Acme Security Ops' })
    await expect(page.locator('#settings')).toContainText('Organization settings updated.')
    await expect(page.locator('[data-org-switcher]')).toBeVisible()
    await expect(page.locator('[data-org-count="true"]')).toContainText('2/2')
    await page.getByRole('button', { name: /Search organizations/ }).click()
    const orgSearch = page.getByRole('dialog', { name: 'Search organizations' }).getByRole('textbox', { name: 'Search organizations' })
    await orgSearch.fill('viewer')
    await expect(page.locator('[data-org-search-result]')).toHaveCount(1)
    await expect(page.locator('[data-org-search-result]')).toContainText('Contoso')
    await orgSearch.fill('')
    await expect(page.locator('[data-org-search-result]')).toHaveCount(2)
    await page.keyboard.press('Escape')
})
