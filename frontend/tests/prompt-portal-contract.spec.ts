import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()

test('prompt portal uses the shared organization session and keeps its worker queue', async () => {
    const page = await readFile(path.join(root, 'src/app/prompt/page.tsx'), 'utf8')
    const aiPage = await readFile(path.join(root, 'src/app/ai/AIWorkspacePage.tsx'), 'utf8')
    const client = await readFile(path.join(root, 'src/app/ai/pageClient.tsx'), 'utf8')
    const chatPane = await readFile(path.join(root, 'src/components/ai/chatPane.tsx'), 'utf8')
    const composer = await readFile(path.join(root, 'src/components/ai/chat/chatComposer.tsx'), 'utf8')
    const routeFrame = await readFile(path.join(root, 'src/components/layout/routeFrame.tsx'), 'utf8')
    const route = await readFile(path.join(root, 'src/app/api/prompt/route.ts'), 'utf8')
    const file = await readFile(path.join(root, 'src/app/api/prompt/file/route.ts'), 'utf8')
    const worker = await readFile(path.join(root, 'src/app/api/prompt/worker/route.ts'), 'utf8')
    const store = await readFile(path.join(root, 'src/utils/promptPortal/store.ts'), 'utf8')
    const policy = await readFile(path.join(root, '../api/src/utils/auth/organizationPagePolicy.ts'), 'utf8')

    expect(page).toContain('redirect(\'/ai\')')
    expect(aiPage).toContain('isHanasandOrganizationMember')
    expect(aiPage).toContain('canUseChatGPT={canUseChatGPT}')
    expect(client).toContain('usePromptPortal')
    expect(client).toContain('canUseChatGPT')
    expect(chatPane).toContain('<ChatTranscript')
    expect(chatPane).toContain('<ChatComposer')
    expect(composer).toContain('provider === \'chatgpt\'')
    expect(composer).toContain('accept=\'image/*\' multiple')
    expect(routeFrame).toContain('!isAiWorkbench')
    expect(route).toContain('requirePromptPortalSession(request)')
    expect(route).not.toContain('createPromptPortalSession')
    expect(route).toContain('body?.action === \'edit\'')
    expect(route).toContain('body?.action === \'delete\'')
    expect(route).toContain('body?.action === \'reorder\'')
    expect(route).toContain('String(form.get(\'conversationId\') || \'\')')
    expect(file).toContain('requirePromptPortalSession(request)')
    expect(policy).toContain('\'/prompt\'')
    expect(worker).toContain('Do not answer in Codex chat.')
    expect(worker).toContain('const MAX_BATCH_ITEMS = 8')
    expect(worker).toContain('batchItem(batch)')
    expect(worker).toContain('promptPortalWorkerToken')
    expect(store).toContain('PROMPT_PORTAL_WORKER_TOKEN')
    expect(store).toContain('timingSafeEqual')
    expect(store).not.toContain('hanasand_prompt_session')
})
