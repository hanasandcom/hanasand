# Sourced by ../install-ssh-gateway.sh.
install_sync_ssh_users() {
    cat >/usr/local/sbin/hanasand-sync-ssh-users <<SH
#!/usr/bin/env bash
set -euo pipefail
if ! timeout 5 "${LXC_BIN}" info >/dev/null 2>&1; then
    echo "LXD is unavailable; skipping VM SSH gateway synchronization"
    exit 0
fi
STATE_DIR="/var/lib/hanasand-ssh-gateway/state"
groupadd -f "${VM_GROUP}"
install -d -m 0750 -o root -g "${VM_GROUP}" "\$STATE_DIR"
sync_one() {
    local name="\$1"
    [ -n "\$name" ] || return 0
    [[ "\$name" =~ ^[A-Za-z0-9][A-Za-z0-9_-]{1,63}\$ ]] || return 0
    [ -n "${LXC_BIN}" ] || return 0
    "${LXC_BIN}" info "\$name" >/dev/null 2>&1 || return 0
    if ! id "\$name" >/dev/null 2>&1; then
        useradd -M -N -g "${VM_GROUP}" -s /bin/bash "\$name"
    elif ! id -nG "\$name" | grep -qw "${VM_GROUP}"; then
        usermod -aG "${VM_GROUP}" "\$name"
    fi
    local home="/var/lib/hanasand-ssh-gateway/home/\$name"
    install -d -m 0750 -o "\$name" -g "${VM_GROUP}" "\$home"
    local passwd_entry
    passwd_entry=\$(getent passwd "\$name" || true)
    if [ "\$(cut -d: -f4 <<<"\$passwd_entry")" != "\$(getent group "${VM_GROUP}" | cut -d: -f3)" ] \
        || [ "\$(cut -d: -f6 <<<"\$passwd_entry")" != "\$home" ] \
        || [ "\$(cut -d: -f7 <<<"\$passwd_entry")" != "/bin/bash" ]; then
        usermod -g "${VM_GROUP}" -d "\$home" -s /bin/bash "\$name"
    fi
    local password
    password=\$("${LXC_BIN}" config get "\$name" user.hanasand.sudo_password 2>/dev/null || true)
    local password_state="\$STATE_DIR/\$name.password"
    if [ -n "\$password" ]; then
        local password_hash
        password_hash=\$(printf '%s' "\$password" | sha256sum | awk '{print \$1}')
        if [ "\$(cat "\$password_state" 2>/dev/null || true)" != "\$password_hash" ]; then
            # Preserve a clear, password-free process marker in auditd EXECVE records.
            if ! printf '%s:%s\\n' "\$name" "\$password" | (exec -a hanasand-lxd-password-sync /usr/sbin/chpasswd); then
                logger -t hanasand-lxd-password-sync -- "action=password_update source=lxd account=\$name result=failure" || true
                return 1
            fi
            logger -t hanasand-lxd-password-sync -- "action=password_update source=lxd account=\$name result=success" || true
            printf '%s\\n' "\$password_hash" >"\$password_state"
        fi
    else
        usermod -p '!' "\$name" >/dev/null 2>&1 || true
        rm -f "\$password_state"
    fi
}
write_sudoers() {
    local tmp
    tmp=\$(mktemp)
    {
        printf '# Generated by install-ssh-gateway.sh. Do not edit by hand.\\n'
        [ -n "${LXC_BIN}" ] || return 0
        "${LXC_BIN}" list --format csv -c n | while IFS=, read -r name; do
            [ -n "\$name" ] || continue
            [[ "\$name" =~ ^[A-Za-z0-9][A-Za-z0-9_-]{1,63}\$ ]] || continue
            "${LXC_BIN}" info "\$name" >/dev/null 2>&1 || continue
            printf '%s ALL=(root) NOPASSWD: /usr/local/sbin/hanasand-vm-ssh-dispatch-root, /usr/local/sbin/hanasand-vm-ssh-dispatch-root *\\n' "\$name"
        done
    } >"\$tmp"
    install -m 0440 -o root -g root "\$tmp" /etc/sudoers.d/hanasand-ssh-gateway
    rm -f "\$tmp"
    visudo -cf /etc/sudoers.d/hanasand-ssh-gateway >/dev/null
}
if [ "\$#" -gt 0 ]; then
    for name in "\$@"; do sync_one "\$name"; done
else
    if [ -n "${LXC_BIN}" ]; then
        "${LXC_BIN}" list --format csv -c n | while IFS=, read -r name; do sync_one "\$name"; done
    fi
fi
write_sudoers
SH
    chmod 0755 /usr/local/sbin/hanasand-sync-ssh-users
}
